import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repositoryRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outputPath = path.join(repositoryRoot, "docs", "support-matrix.md");

function displayMaturity(value) {
  return `${value[0].toUpperCase()}${value.slice(1)}`;
}

function displayMcp(value) {
  return {
    "not-applicable": "not applicable",
    "minimal-handwritten": "No, minimal handwritten scaffold",
    "official-sdk": "Yes, official Tier 1 SDK"
  }[value];
}

function displayOtel(value) {
  return value === "otlp" ? "Yes, OTLP" : "No";
}

function displayBoolean(value) {
  return value ? "Yes" : "No";
}

export async function renderSupportMatrix() {
  const catalog = JSON.parse(await readFile(path.join(repositoryRoot, "catalog.json"), "utf8"));
  const targets = await Promise.all(catalog.spec.targetProfiles.map(async (targetPath) =>
    JSON.parse(await readFile(path.join(repositoryRoot, targetPath), "utf8"))));

  const targetRows = targets.map((target) => {
    const verified = target.spec.documentation.verifiedAt ?? "No";
    return `| ${target.metadata.name} | ${displayMaturity(target.spec.maturity)} | ${target.spec.agentHosting.join("; ")} | ${target.spec.mcpHosting.join("; ")} | ${target.spec.artifact.registry} OCI, ${target.spec.artifact.architectures.map((item) => item.replace("linux/", "")).join("/")} | ${target.spec.events.mode} | ${target.spec.identity.deployment} | ${verified} |`;
  }).join("\n");

  const templateRows = catalog.spec.templates.map((template) =>
    `| \`${template.id}\` \`${template.version}\` | ${template.conformance.framework} | ${displayBoolean(template.conformance.deterministicMode)} | ${displayMcp(template.conformance.mcp)} | ${displayOtel(template.conformance.openTelemetry)} | ${displayBoolean(template.conformance.level === "gold")} |`
  ).join("\n");

  return `<!-- Generated by scripts/generate-support-matrix.mjs. Do not edit directly. -->

# Platform support matrix

This matrix is generated from the current catalog and target-profile manifests. \`Scaffold\` means
repository content and a contract exist. It does not mean the provider path has passed live
verification.

| target | maturity | agent hosting | MCP hosting | artifact | event/reconciliation | deployment identity | live verified |
| --- | --- | --- | --- | --- | --- | --- | --- |
${targetRows}

Promotion to Preview or Stable requires a dated clean-environment run covering interactive login,
secretless collector access, negative identity tests, build/sign/SBOM/provenance, deployment by
immutable digest, agent-to-MCP identity, graph convergence, suspension and teardown.

## Template conformance

| template release | framework | deterministic mode | official MCP SDK | OpenTelemetry | Gold |
| --- | --- | --- | --- | --- | --- |
${templateRows}

Template conformance and provider maturity are independent. The portable MCP runtime can pass Gold
locally while every deployment target remains Scaffold until its dated live gate passes.

## Promotion evidence

Each promoted target row must link to a guide generated from its target profile and include:

- exact target and framework versions;
- artifact architecture and immutable digest verification;
- interactive login used for the first human test;
- production workload-identity setup;
- event-assisted refresh and periodic reconciliation evidence;
- one agent and one MCP server test without a model;
- negative identity and network tests;
- teardown and trust-revocation result;
- live verification date.

<!-- SCREENSHOT TODO: supported-platform matrix from HodosGraph after it is generated from these manifests. -->
`;
}

export async function checkSupportMatrix() {
  const expected = await renderSupportMatrix();
  const current = await readFile(outputPath, "utf8");
  if (current !== expected) throw new Error("docs/support-matrix.md is stale; run npm run docs:matrix");
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    if (process.argv.includes("--check")) {
      await checkSupportMatrix();
      console.log("Support matrix is current.");
    } else {
      await writeFile(outputPath, await renderSupportMatrix(), "utf8");
      console.log("Generated docs/support-matrix.md.");
    }
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
